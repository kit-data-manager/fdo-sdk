import { readdir, readFile, writeFile } from "node:fs/promises"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const here = dirname(fileURLToPath(import.meta.url))

const profilesDir = join(here, "..", "..", "..", "assets", "creep-profiles")
const outFile = join(here, "..", "src", "creepProfiles.ts")

const files = (await readdir(profilesDir))
    .filter((f) => f.endsWith(".json"))
    .sort()

const typeFor = (cardinality) => {
    const multi = cardinality.includes("n")
    const optional = cardinality.startsWith("0")
    const base = multi ? "string | string[]" : "string"
    return { base, optional }
}

const profiles = []
for (const file of files) {
    const json = JSON.parse(await readFile(join(profilesDir, file), "utf8"))
    const name = json.name ?? file.replace(/\.json$/, "")
    const props = []
    for (const prop of json.Schema.Properties) {
        const { base, optional } = typeFor(
            prop.Properties?.Cardinality ?? "1",
        )
        props.push({
            key: prop.Name,
            comment: prop.Description,
            title: prop.Title ?? prop.Name,
            base,
            optional,
            pid: prop.Type,
        })
    }
    profiles.push({ name, pid: json.Identifier, props })
}

const key = (name) =>
    /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(name) ? name : JSON.stringify(name)
const camel = (name) =>
    name.charAt(0).toLowerCase() + name.slice(1)

let out = ""
out += "/* Generated by " + here.split("/").pop() + "/generate-creep-profiles.mjs. Do not edit manually. */\n"
out += 'import type { Attribute, ProfileDefinition, RecordValue } from "@fdo-sdk/primitives"\n'
out += 'import { ConcreteProfile } from "@fdo-sdk/primitives"\n'
out += "\n"

for (const { name, pid, props } of profiles) {
    out += "export type " + name + "ProfileAttributes = {\n"
    for (const prop of props) {
        out += "    /** " + prop.comment + " */\n"
        out +=
            "    " +
            key(prop.key) +
            (prop.optional ? "?" : "") +
            ": " +
            prop.base +
            "\n"
    }
    out += "}\n\n"

    out += "export const " + camel(name) + "Attributes = {\n"
    for (const prop of props) {
        out += "    " + key(prop.key) + ": {\n"
        out += '        pid: "' + prop.pid + '",\n'
        out += '        readableName: "' + prop.title + '",\n'
        out += "    },\n"
    }
    out +=
        "} as const satisfies Record<keyof " +
        name +
        "ProfileAttributes, Attribute<RecordValue>>\n\n"

    out +=
        "export const " +
        name +
        "ProfileDefinition: ProfileDefinition<" +
        name +
        "ProfileAttributes> = {\n"
    out += '    pid: "' + pid + '",\n'
    out += '    readableName: "' + name + '",\n'
    out += "    mapping: {\n"
    for (const prop of props) {
        out +=
            "        " +
            key(prop.key) +
            ": " +
            JSON.stringify(prop.pid) +
            ",\n"
    }
    out += "    },\n"
    out += "}\n\n"

    out +=
        "export const " +
        name +
        "Profile = new ConcreteProfile(" +
        name +
        "ProfileDefinition)\n\n"
}

out += "export const creepProfiles = {\n"
for (const { name } of profiles) {
    out += "    " + key(name) + ": " + name + "Profile,\n"
}
out += "}\n"

await writeFile(outFile, out)

console.log("Wrote " + outFile)
console.log(
    "Profiles: " +
        profiles.map((p) => p.name).join(", ") +
        " (" +
        profiles.length +
        " total)",
)
